/* ---- Language switcher logic ---- */
function getLang() {
  return localStorage.getItem('agronord-lang') || 'ru';
}

function setLang(lang) {
  localStorage.setItem('agronord-lang', lang);
  applyLang(lang);
  updateSwitcher(lang);
  document.documentElement.lang = lang;
}

function applyLang(lang) {
  // если язык не передан — берём сохранённый, чтобы случайный вызов
  // без аргумента не сбрасывал интерфейс на русский
  if (!lang) lang = getLang();
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const t = translations[key];
    if (!t) return;
    const text = t[lang] || t.ru;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = text;
    } else if (el.hasAttribute('data-i18n-html')) {
      el.innerHTML = text;
    } else {
      el.textContent = text;
    }
  });

  // Update title
  const titleEl = document.querySelector('[data-i18n-title]');
  if (titleEl) {
    const key = titleEl.getAttribute('data-i18n-title');
    const t = translations[key];
    if (t) document.title = (t[lang] || t.ru) + ' — AgroNord';
  }
}

function updateSwitcher(lang) {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

function initI18n() {
  const lang = getLang();
  applyLang(lang);
  updateSwitcher(lang);
  document.documentElement.lang = lang;

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });
}

document.addEventListener('DOMContentLoaded', initI18n);
